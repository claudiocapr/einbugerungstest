/**
 * Einprägen: Verb + Fall. Which case does the verb's object take?
 * Every item has an example whose object phrases (`obj`, in the order
 * Dativ, Akkusativ) are checked against the form tables in the tests.
 */
import type { Text2 } from '../../types.ts';

/** dat = Dativ, akk = Akkusativ, datakk = Person im Dativ + Sache im Akkusativ, nom = zwei Nominative. */
export type VerbCase = 'nom' | 'akk' | 'dat' | 'datakk';

export interface VerbCaseItem {
  key: string;
  verb: string;
  /** Shown under the verb when the case depends on the reading: "(+ Person)". */
  cue?: Text2;
  en: string;
  c: VerbCase;
  example: string;
  exampleEn: string;
  /** The object phrases in the example: [Dativ, Akkusativ] for datakk, else the one object (or predicate noun). */
  obj: string[];
  tip: Text2;
}

